def sql_in(columna: str, valores: tuple[str, ...]) -> str:
    """Genera la expresión SQL `columna IN ('A', 'B', ...)` para un CHECK."""
    lista = ", ".join(f"'{v}'" for v in valores)
    return f"{columna} IN ({lista})"